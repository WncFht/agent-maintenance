"""Separate staged formatting from pre-commit's unstaged-change handling."""

import argparse
import re
import shlex
import subprocess
import sys
from pathlib import Path

import yaml
from identify.identify import tags_from_path


def format_staged(root):
    """Run declared git-format-staged hooks directly, before framework stashing."""
    config = yaml.safe_load((root / ".pre-commit-config.yaml").read_text())
    paths = (
        subprocess.check_output(
            ["git", "diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"],
            cwd=root,
        )
        .decode("utf-8", "surrogateescape")
        .split("\0")
    )
    for repository in config["repos"]:
        for hook in repository["hooks"]:
            if "manual" not in hook.get("stages", []):
                continue
            command = shlex.split(hook["entry"])
            if (
                repository["repo"] != "local"
                or hook["language"] != "system"
                or Path(command[0]).name != "git-format-staged"
            ):
                message = (
                    "The manual stage is reserved for local git-format-staged hooks"
                )
                raise SystemExit(message)
            selected = []
            for name in paths:
                if not name or not (root / name).is_file():
                    continue
                tags = tags_from_path(str(root / name))
                if (
                    re.search(config.get("files", ""), name)
                    and not re.search(config.get("exclude", "^$"), name)
                    and re.search(hook.get("files", ""), name)
                    and not re.search(hook.get("exclude", "^$"), name)
                    and set(hook.get("types", ["file"])) <= tags
                    and (not hook.get("types_or") or set(hook["types_or"]) & tags)
                    and not set(hook.get("exclude_types", [])) & tags
                ):
                    selected.append(name)
            for start in range(0, len(selected), 100):
                subprocess.run(
                    [*command, *selected[start : start + 100]],
                    cwd=root,
                    check=True,
                )


def install(root, hook_type="pre-commit"):
    """Preserve foreign hook configurations and replace only owned hooks."""
    root = Path(root).resolve()
    custom = subprocess.run(
        ["git", "config", "--get", "core.hooksPath"],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    if custom.returncode == 0:
        message = "core.hooksPath is configured; integrate the two phases manually"
        raise SystemExit(message)
    hook_dir = Path(
        subprocess.check_output(
            ["git", "rev-parse", "--git-path", "hooks"],
            cwd=root,
            text=True,
        ).strip()
    )
    if not hook_dir.is_absolute():
        hook_dir = root / hook_dir
    hook = hook_dir / hook_type
    delegate = hook_dir / f"{hook_type}.checks"
    for path in (hook, delegate):
        if path.exists() and not any(
            marker in path.read_text()
            for marker in (
                "# File generated by pre-commit:",
                "# agent-maintenance two-phase hook",
                "# agent-maintenance managed hook",
            )
        ):
            message = f"Refusing to overwrite foreign hook: {path}"
            raise SystemExit(message)
    if hook.exists() and any(
        marker in hook.read_text()
        for marker in (
            "# agent-maintenance two-phase hook",
            "# agent-maintenance managed hook",
        )
    ):
        hook.unlink()
    subprocess.run(
        [sys.executable, "-m", "pre_commit", "install", "--hook-type", hook_type],
        cwd=root,
        check=True,
    )
    hook.replace(delegate)
    python = shlex.quote(sys.executable)
    format_command = (
        f"{python} {shlex.quote(str(Path(__file__).resolve()))} --format-staged\n"
        if hook_type == "pre-commit"
        else ""
    )
    hook.write_text(
        "#!/bin/sh\n# agent-maintenance managed hook\nset -eu\n"
        f'export PATH={shlex.quote(str(Path(sys.executable).parent))}:"$PATH"\n'
        f"{format_command}"
        f'exec {shlex.quote(str(delegate))} "$@"\n'
    )
    hook.chmod(0o755)


def main():
    """Install the hook for the selected repository."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--format-staged", action="store_true")
    args = parser.parse_args()
    if args.format_staged:
        format_staged(args.root.resolve())
    else:
        install(args.root)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
